function isUiLanguage(value: unknown): value is UiLanguage {
  return value === "en" || value === "zh-CN";
}

export function applyLanguage(language: UiLanguage): void {
  currentLanguage = language;
  document.documentElement.lang = language === "zh-CN" ? "zh-CN" : "en";
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n as MessageKey;
    element.textContent = t(key);
  });
  document.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder as MessageKey;
    element.placeholder = t(key);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((element) => {
    const key = element.dataset.i18nTitle as MessageKey;
    element.title = t(key);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel as MessageKey;
    element.setAttribute("aria-label", t(key));
  });
}

export async function initializeLanguage(): Promise<UiLanguage> {
  const stored = await chrome.storage.local.get("uiLanguage");
  const language = isUiLanguage(stored.uiLanguage)
    ? stored.uiLanguage
    : navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
  applyLanguage(language);
  chrome.storage.onChanged.addListener((changes, area) => {
    if (area === "local" && isUiLanguage(changes.uiLanguage?.newValue)) {
      applyLanguage(changes.uiLanguage.newValue);
    }
  });
  return language;
}

export async function saveLanguage(language: UiLanguage): Promise<void> {
  applyLanguage(language);
  await chrome.storage.local.set({ uiLanguage: language });
}
